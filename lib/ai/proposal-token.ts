import crypto from "node:crypto";

function getProposalSecret(): string {
  return (
    process.env.INTEGRATION_ENCRYPTION_KEY?.trim() ||
    process.env.SUPABASE_SERVICE_ROLE_KEY?.trim() ||
    (process.env.NODE_ENV !== "production" ? "dev-proposal-signing-secret" : "")
  );
}

/**
 * Creates a tamper-proof HMAC-SHA256 token signing an AI proposal for Human-in-the-Loop execution.
 */
export function signAiProposalToken(params: {
  userId: string;
  entityId: string;
  proposalType: string;
  proposalPayload: Record<string, unknown>;
}): string {
  const secret = getProposalSecret();
  if (!secret) {
    return "";
  }

  const payloadStr = JSON.stringify({
    u: params.userId,
    e: params.entityId,
    t: params.proposalType,
    p: params.proposalPayload,
    exp: Date.now() + 24 * 60 * 60 * 1000, // 24 hours valid
  });

  const encodedPayload = Buffer.from(payloadStr, "utf8").toString("base64url");
  const hmac = crypto
    .createHmac("sha256", secret)
    .update(encodedPayload)
    .digest("base64url");

  return `${encodedPayload}.${hmac}`;
}

/**
 * Verifies that a proposal was indeed generated by the server's AI agent for this specific user & entity.
 */
export function verifyAiProposalToken(
  token: string | undefined | null,
  params: {
    userId: string;
    entityId: string;
    proposalType: string;
  }
): { ok: boolean; isAiVerified: boolean; error?: string } {
  if (!token || typeof token !== "string" || !token.includes(".")) {
    return { ok: true, isAiVerified: false };
  }

  const secret = getProposalSecret();
  if (!secret) {
    return { ok: true, isAiVerified: false };
  }

  const parts = token.split(".");
  if (parts.length !== 2) {
    return { ok: false, isAiVerified: false, error: "AI taklif imzosi formati notoʻgʻri." };
  }

  const [encodedPayload, providedHmac] = parts;
  const expectedHmac = crypto
    .createHmac("sha256", secret)
    .update(encodedPayload)
    .digest("base64url");

  const bufProvided = Buffer.from(providedHmac, "utf8");
  const bufExpected = Buffer.from(expectedHmac, "utf8");

  if (bufProvided.length !== bufExpected.length || !crypto.timingSafeEqual(bufProvided, bufExpected)) {
    return { ok: false, isAiVerified: false, error: "AI taklif imzosi notoʻgʻri yoki soxtalashtirilgan." };
  }

  try {
    const data = JSON.parse(Buffer.from(encodedPayload, "base64url").toString("utf8"));
    if (data.exp && data.exp < Date.now()) {
      return { ok: false, isAiVerified: false, error: "AI taklifining amal qilish muddati oʻtgan." };
    }
    if (data.u !== params.userId || data.e !== params.entityId || data.t !== params.proposalType) {
      return { ok: false, isAiVerified: false, error: "AI taklif konteksti (foydalanuvchi/korxona/amal) mos kelmadi." };
    }
    return { ok: true, isAiVerified: true };
  } catch {
    return { ok: false, isAiVerified: false, error: "AI taklif tokeni buzilgan." };
  }
}
